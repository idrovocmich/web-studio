// Resolves the active brand and writes its CSS, specimen data and logos for Astro.
//   WS_BRAND=voltio-labs pnpm build      → uses a fixture from @idrovocmich/brand-contract
//   WS_BRAND_DIR=../my-brand pnpm build  → uses a brand folder that contains brand.json
// Runs with Node's built-in TypeScript type stripping (Node 22.18+ / 24).
import { buildTokens } from "@idrovocmich/tokens";
import { loadBrand } from "@idrovocmich/brand-contract/node";
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fixturesDir = resolve(appDir, "../../packages/brand-contract/fixtures");
const DEFAULT_BRAND = "casa-terracota";

const brandDir = process.env["WS_BRAND_DIR"]
  ? resolve(process.cwd(), process.env["WS_BRAND_DIR"])
  : join(fixturesDir, process.env["WS_BRAND"] ?? DEFAULT_BRAND);

let loaded;
try {
  loaded = await loadBrand(brandDir);
} catch (error) {
  console.error(`\n✖ ${(error as Error).message}\n`);
  process.exit(1);
}

const { brand, tokens, css, contrast } = loaded;
const { light, dark } = await buildTokens(tokens);

const generatedDir = join(appDir, "src/generated");
const publicBrandDir = join(appDir, "public/brand");
await rm(publicBrandDir, { recursive: true, force: true });
await mkdir(generatedDir, { recursive: true });

// Copy every declared logo (and self-hosted font) keeping its path relative to the brand folder.
const assetFiles = [...Object.values(loaded.assets.logos), ...loaded.assets.fonts];
for (const file of assetFiles) {
  const target = join(publicBrandDir, relative(loaded.dir, file));
  await mkdir(dirname(target), { recursive: true });
  await cp(file, target);
}

const header = `/* Brand "${brand.id}" — generated by scripts/build-brand.ts. Do not edit. */\n`;
await writeFile(join(generatedDir, "brand-tokens.css"), header + css.tokens);
await writeFile(join(generatedDir, "brand-theme.css"), header + css.theme);
await writeFile(
  join(generatedDir, "brand-data.json"),
  `${JSON.stringify({ brand, light, dark, contrast }, null, 2)}\n`,
);

console.log(
  `✔ Marca activa: ${brand.name} (${brand.id}) — ${contrast.length} pares de contraste AA correctos.`,
);
